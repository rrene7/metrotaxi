/* Metro Taxi v0.8.3 — navigation links: test no fabricated coordinates */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const code=fs.readFileSync(path.join(__dirname,'../static/navigation.js'),'utf8');
const context={window:{}};vm.createContext(context);vm.runInContext(code,context);
const {urls,navLinks}=context.window.MTNavigation;
let r=urls(9.0881234,-79.2871234);
assert.equal(r.waze,'https://waze.com/ul?ll=9.0881234%2C-79.2871234&navigate=yes');
assert.equal(r.google,'https://www.google.com/maps/dir/?api=1&destination=9.0881234%2C-79.2871234&travelmode=driving&dir_action=navigate');
assert.equal(urls(null,null),null);
assert.equal(urls('9.1','-79.1'),null);
assert.equal(urls(NaN,-79.2),null);
assert.equal(urls(200,-79.2),null);
assert.equal(navLinks({status:'offered',pickup_lat:9,pickup_lng:-79}), '');
assert.equal(navLinks({status:'cancelled',pickup_lat:9,pickup_lng:-79}), '');
const accepted=navLinks({status:'accepted',pickup_lat:9.0881234,pickup_lng:-79.2871234,pickup_accuracy_m:17.9,dest_lat:9.111,dest_lng:-79.222});
assert.match(accepted,/Navegar a recogida con Waze/);
assert.match(accepted,/9.0881234%2C-79.2871234/);
assert.doesNotMatch(accepted,/Waze al destino/);
assert.match(accepted,/±18 m/);
const ongoing=navLinks({status:'inprogress',pickup_lat:9.0881234,pickup_lng:-79.2871234,dest_lat:9.111,dest_lng:-79.222});
assert.match(ongoing,/Waze al destino/);
assert.match(ongoing,/9.111%2C-79.222/);
const empty=navLinks({status:'accepted',pickup:'Frente a la iglesia'});
assert.match(empty,/no tiene coordenadas verificables/);
assert.doesNotMatch(empty,/href=/);
console.log('OK: navegación Waze/Google Maps; estados y coordenadas explícitas.');
